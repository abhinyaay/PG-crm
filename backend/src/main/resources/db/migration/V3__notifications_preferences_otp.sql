-- =====================================================================
-- V3: notification preferences, organization channel settings, delivery
-- suppression (opt-out / bounce) and one-time codes for password reset.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Contact-point state used when deciding whether to use EMAIL / SMS
-- ---------------------------------------------------------------------
ALTER TABLE users
    ADD COLUMN preferred_language VARCHAR(5) NOT NULL DEFAULT 'en',
    ADD COLUMN phone_verified_at  TIMESTAMPTZ,
    ADD COLUMN sms_opt_out_at     TIMESTAMPTZ,      -- also set from DLT STOP replies; suppresses SMS
    ADD COLUMN email_bounced_at   TIMESTAMPTZ;      -- set by bounce handling; suppresses EMAIL

-- residents without a portal login still need opt-out / bounce state
ALTER TABLE tenants
    ADD COLUMN sms_opt_out_at   TIMESTAMPTZ,
    ADD COLUMN email_bounced_at TIMESTAMPTZ;

-- ---------------------------------------------------------------------
-- Outbox: urgency (quiet hours bypass) and template variables
-- ---------------------------------------------------------------------
ALTER TABLE notifications
    ADD COLUMN urgent          BOOLEAN NOT NULL DEFAULT FALSE,
    -- variables for fixed SMS (DLT) templates and email extras such as a one-time code; cleared after
    -- delivery for sensitive types so codes do not linger in the table
    ADD COLUMN template_params JSONB;

-- ---------------------------------------------------------------------
-- Per-user channel preferences (absence of a row = matrix default)
-- ---------------------------------------------------------------------
CREATE TABLE notification_preferences (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT      NOT NULL REFERENCES users (id),
    notification_type VARCHAR(40) NOT NULL,
    channel           VARCHAR(10) NOT NULL,
    enabled           BOOLEAN     NOT NULL,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_notification_preferences UNIQUE (user_id, notification_type, channel),
    CONSTRAINT ck_notification_preferences_channel CHECK (channel IN ('IN_APP', 'EMAIL', 'SMS', 'PUSH'))
);

-- ---------------------------------------------------------------------
-- Organization-wide switches (e.g. turn off SMS for a type to control cost)
-- ---------------------------------------------------------------------
CREATE TABLE organization_notification_settings (
    organization_id   BIGINT      NOT NULL REFERENCES organizations (id),
    notification_type VARCHAR(40) NOT NULL,
    channel           VARCHAR(10) NOT NULL,
    enabled           BOOLEAN     NOT NULL,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by        BIGINT,
    PRIMARY KEY (organization_id, notification_type, channel),
    CONSTRAINT ck_org_notification_settings_channel CHECK (channel IN ('IN_APP', 'EMAIL', 'SMS', 'PUSH'))
);

-- ---------------------------------------------------------------------
-- One-time codes for "forgot password" and portal "set your password"
-- ---------------------------------------------------------------------
CREATE TABLE password_reset_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (id),
    channel       VARCHAR(10) NOT NULL,
    purpose       VARCHAR(10) NOT NULL DEFAULT 'RESET',
    code_hash     VARCHAR(64) NOT NULL,                -- SHA-256 hex; the code itself is never stored here
    expires_at    TIMESTAMPTZ NOT NULL,
    attempts      INTEGER     NOT NULL DEFAULT 0,
    consumed_at   TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by_ip VARCHAR(45),
    CONSTRAINT ck_password_reset_tokens_channel CHECK (channel IN ('EMAIL', 'SMS')),
    CONSTRAINT ck_password_reset_tokens_purpose CHECK (purpose IN ('RESET', 'SETUP')),
    CONSTRAINT ck_password_reset_tokens_attempts CHECK (attempts >= 0)
);
CREATE INDEX idx_password_reset_tokens_user ON password_reset_tokens (user_id, created_at DESC);
CREATE INDEX idx_password_reset_tokens_created ON password_reset_tokens (created_at);

-- the refresh-token cleanup job checks that no live token still points at a row it deletes
CREATE INDEX idx_refresh_tokens_replaced_by ON refresh_tokens (replaced_by_token_id)
    WHERE replaced_by_token_id IS NOT NULL;
