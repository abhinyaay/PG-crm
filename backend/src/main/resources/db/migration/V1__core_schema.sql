    updated_by          BIGINT,
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_maintenance_ticket UNIQUE (ticket_number),
    CONSTRAINT ck_maintenance_category CHECK (category IN
        ('ELECTRICAL', 'PLUMBING', 'CARPENTRY', 'CLEANING', 'APPLIANCE', 'INTERNET', 'PEST_CONTROL', 'OTHER')),
    CONSTRAINT ck_maintenance_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_maintenance_status CHECK (status IN
        ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED', 'CANCELLED'))
);
CREATE INDEX idx_maintenance_property_status ON maintenance_requests (property_id, status);
CREATE INDEX idx_maintenance_assignee_status ON maintenance_requests (assigned_to_user_id, status);
CREATE INDEX idx_maintenance_tenant ON maintenance_requests (tenant_id);
CREATE INDEX idx_maintenance_sla_watch ON maintenance_requests (sla_due_at)
    WHERE sla_breached = FALSE AND status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS');

CREATE TABLE maintenance_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT      NOT NULL REFERENCES maintenance_requests (id),
    from_status VARCHAR(20),
    to_status   VARCHAR(20) NOT NULL,
    changed_by  BIGINT REFERENCES users (id),
    note        VARCHAR(1000),
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_maintenance_history_request ON maintenance_status_history (request_id, changed_at);

-- ---------------------------------------------------------------------
-- Complaints
-- ---------------------------------------------------------------------
CREATE SEQUENCE complaint_number_seq;

CREATE TABLE complaints (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_number    VARCHAR(30)  NOT NULL,
    organization_id     BIGINT       NOT NULL REFERENCES organizations (id),
    property_id         BIGINT       NOT NULL REFERENCES properties (id),
    tenant_id           BIGINT REFERENCES tenants (id),
    raised_by_user_id   BIGINT       NOT NULL REFERENCES users (id),
    category            VARCHAR(30)  NOT NULL,
    priority            VARCHAR(20)  NOT NULL,
    subject             VARCHAR(150) NOT NULL,
    description         TEXT         NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    assigned_to_user_id BIGINT REFERENCES users (id),
    escalation_level    INTEGER      NOT NULL DEFAULT 0,
    escalated_at        TIMESTAMPTZ,
    due_at              TIMESTAMPTZ  NOT NULL,
    resolution          TEXT,
    resolved_at         TIMESTAMPTZ,
    closed_at           TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_by          BIGINT,
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_complaints_number UNIQUE (complaint_number),
    CONSTRAINT ck_complaints_category CHECK (category IN
        ('NOISE', 'CLEANLINESS', 'FOOD', 'STAFF_BEHAVIOUR', 'SECURITY', 'BILLING', 'ROOMMATE', 'OTHER')),
    CONSTRAINT ck_complaints_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_complaints_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'ESCALATED', 'RESOLVED', 'CLOSED')),
    CONSTRAINT ck_complaints_escalation CHECK (escalation_level BETWEEN 0 AND 3)
);
CREATE INDEX idx_complaints_property_status ON complaints (property_id, status);
CREATE INDEX idx_complaints_assignee ON complaints (assigned_to_user_id, status);
CREATE INDEX idx_complaints_tenant ON complaints (tenant_id);
CREATE INDEX idx_complaints_due_watch ON complaints (due_at) WHERE status IN ('OPEN', 'IN_PROGRESS', 'ESCALATED');

CREATE TABLE complaint_comments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id   BIGINT      NOT NULL REFERENCES complaints (id),
    author_user_id BIGINT      NOT NULL REFERENCES users (id),
    body           TEXT        NOT NULL,
    internal       BOOLEAN     NOT NULL DEFAULT FALSE,   -- staff-only note, hidden from tenants
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_complaint_comments_complaint ON complaint_comments (complaint_id, created_at);

CREATE TABLE complaint_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id  BIGINT      NOT NULL REFERENCES complaints (id),
    event_type    VARCHAR(20) NOT NULL,
    from_status   VARCHAR(20),
    to_status     VARCHAR(20),
    actor_user_id BIGINT REFERENCES users (id),         -- NULL => system (scheduler)
    details       VARCHAR(1000),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_complaint_events_type CHECK (event_type IN
        ('CREATED', 'ASSIGNED', 'STATUS_CHANGED', 'ESCALATED', 'COMMENTED'))
);
CREATE INDEX idx_complaint_events_complaint ON complaint_events (complaint_id, created_at);

-- ---------------------------------------------------------------------
-- Notifications (outbox-style: rows are written in the business transaction,
-- a dispatcher delivers them asynchronously)
-- ---------------------------------------------------------------------
CREATE TABLE notifications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id   BIGINT REFERENCES organizations (id),
    recipient_user_id BIGINT REFERENCES users (id),
    recipient_address VARCHAR(255),
    channel           VARCHAR(10)  NOT NULL,
    type              VARCHAR(40)  NOT NULL,
    title             VARCHAR(200) NOT NULL,
    body              TEXT         NOT NULL,
    reference_type    VARCHAR(40),
    reference_id      BIGINT,
    status            VARCHAR(10)  NOT NULL,
    attempts          INTEGER      NOT NULL DEFAULT 0,
    next_attempt_at   TIMESTAMPTZ,
    last_error        VARCHAR(500),
    sent_at           TIMESTAMPTZ,
    read_at           TIMESTAMPTZ,
    dedup_key         VARCHAR(150),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_notifications_channel CHECK (channel IN ('IN_APP', 'EMAIL', 'SMS', 'PUSH')),
    CONSTRAINT ck_notifications_status CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT ck_notifications_recipient CHECK (recipient_user_id IS NOT NULL OR recipient_address IS NOT NULL)
);
CREATE UNIQUE INDEX uk_notifications_dedup ON notifications (dedup_key, channel) WHERE dedup_key IS NOT NULL;
CREATE INDEX idx_notifications_inbox ON notifications (recipient_user_id, created_at DESC) WHERE channel = 'IN_APP';
CREATE INDEX idx_notifications_dispatch ON notifications (next_attempt_at) WHERE status = 'PENDING';

-- ---------------------------------------------------------------------
-- Audit trail (append-only)
-- ---------------------------------------------------------------------
CREATE TABLE audit_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT,
    actor_user_id   BIGINT,
    actor_email     VARCHAR(255),
    action          VARCHAR(50)  NOT NULL,
    entity_type     VARCHAR(50)  NOT NULL,
    entity_id       BIGINT,
    details         JSONB,
    ip_address      VARCHAR(45),
    correlation_id  VARCHAR(64),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_org_created ON audit_logs (organization_id, created_at DESC);
CREATE INDEX idx_audit_actor ON audit_logs (actor_user_id, created_at DESC);

-- ---------------------------------------------------------------------
-- Distributed scheduler lock (ShedLock) - keeps jobs single-run across replicas
-- ---------------------------------------------------------------------
CREATE TABLE shedlock (
    name       VARCHAR(64)  PRIMARY KEY,
    lock_until TIMESTAMPTZ  NOT NULL,
    locked_at  TIMESTAMPTZ  NOT NULL,
    locked_by  VARCHAR(255) NOT NULL
);
