-- =====================================================================
-- PG Management Platform - core transactional schema
-- Conventions:
--   * BIGINT identity primary keys
--   * created_at / updated_at / created_by / updated_by on mutable aggregates
--   * deleted_at for soft-deleted master data (users, properties, rooms, beds, tenants)
--   * version column for JPA optimistic locking on contended rows
--   * Enumerations stored as VARCHAR + CHECK constraint (readable, easy to evolve)
--   * Money as NUMERIC(12,2); timestamps as TIMESTAMPTZ (UTC); business dates as DATE
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;  -- needed for EXCLUDE constraints mixing = and &&
CREATE EXTENSION IF NOT EXISTS pg_trgm;     -- fast ILIKE search on tenant names

-- ---------------------------------------------------------------------
-- Tenancy boundary: an organization is a PG operator (the SaaS customer)
-- ---------------------------------------------------------------------
CREATE TABLE organizations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150) NOT NULL,
    slug            VARCHAR(80)  NOT NULL,
    contact_email   VARCHAR(255),
    contact_phone   VARCHAR(20),
    status          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      BIGINT,
    updated_by      BIGINT,
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_organizations_slug UNIQUE (slug),
    CONSTRAINT ck_organizations_status CHECK (status IN ('ACTIVE', 'SUSPENDED'))
);

-- ---------------------------------------------------------------------
-- Identity & access
-- ---------------------------------------------------------------------
CREATE TABLE roles (
    id          SMALLINT     PRIMARY KEY,
    name        VARCHAR(30)  NOT NULL,
    description VARCHAR(255) NOT NULL,
    CONSTRAINT uk_roles_name UNIQUE (name)
);

INSERT INTO roles (id, name, description) VALUES
