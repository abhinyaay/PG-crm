    organization_id    BIGINT       NOT NULL REFERENCES organizations (id),
    property_id        BIGINT       NOT NULL REFERENCES properties (id),  -- current / onboarding property
    user_id            BIGINT REFERENCES users (id),                       -- optional self-service login
    full_name          VARCHAR(150) NOT NULL,
    email              VARCHAR(255),
    phone              VARCHAR(20)  NOT NULL,
    gender             VARCHAR(10),
    date_of_birth      DATE,
    occupation         VARCHAR(100),
    organization_name  VARCHAR(150),                                       -- employer / college
    permanent_address  TEXT,
    status             VARCHAR(20)  NOT NULL DEFAULT 'PROSPECTIVE',
    joining_date       DATE,
    move_out_date      DATE,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by         BIGINT,
    updated_by         BIGINT,
    deleted_at         TIMESTAMPTZ,
    version            BIGINT       NOT NULL DEFAULT 0,
