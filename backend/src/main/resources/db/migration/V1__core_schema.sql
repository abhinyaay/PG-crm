-- at most one live reservation per bed and per tenant
CREATE UNIQUE INDEX uk_bookings_reserved_bed ON bookings (bed_id) WHERE status = 'RESERVED';
CREATE UNIQUE INDEX uk_bookings_reserved_tenant ON bookings (tenant_id) WHERE status = 'RESERVED';
CREATE INDEX idx_bookings_expiry ON bookings (reserved_until) WHERE status = 'RESERVED';
CREATE INDEX idx_bookings_property_status ON bookings (property_id, status);

CREATE TABLE allocations (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id        BIGINT         NOT NULL REFERENCES organizations (id),
    property_id            BIGINT         NOT NULL REFERENCES properties (id),
    tenant_id              BIGINT         NOT NULL REFERENCES tenants (id),
    bed_id                 BIGINT         NOT NULL REFERENCES beds (id),
    booking_id             BIGINT REFERENCES bookings (id),
    previous_allocation_id BIGINT REFERENCES allocations (id),
    status                 VARCHAR(20)    NOT NULL,
    start_date             DATE           NOT NULL,
    end_date               DATE,                       -- exclusive; NULL while active
    notice_date            DATE,
    expected_end_date      DATE,
    end_reason             VARCHAR(20),
    monthly_rent           NUMERIC(12, 2) NOT NULL,    -- snapshot of agreed rent
    security_deposit       NUMERIC(12, 2) NOT NULL,    -- snapshot of agreed deposit
    created_at             TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by             BIGINT,
    updated_by             BIGINT,
    version                BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_allocations_status CHECK (status IN ('ACTIVE', 'ENDED', 'TRANSFERRED')),
    CONSTRAINT ck_allocations_end_reason CHECK (end_reason IS NULL OR end_reason IN ('CHECK_OUT', 'TRANSFER')),
    CONSTRAINT ck_allocations_active_open CHECK ((status = 'ACTIVE') = (end_date IS NULL)),
    CONSTRAINT ck_allocations_dates CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_allocations_money CHECK (monthly_rent >= 0 AND security_deposit >= 0),
    -- The database itself refuses two occupancies of the same bed (or the same tenant)
    -- whose [start, end) date ranges overlap - including back-dated or historical rows.
    CONSTRAINT ex_allocations_bed_overlap
        EXCLUDE USING gist (bed_id WITH =, daterange(start_date, end_date, '[)') WITH &&),
    CONSTRAINT ex_allocations_tenant_overlap
        EXCLUDE USING gist (tenant_id WITH =, daterange(start_date, end_date, '[)') WITH &&)
);
CREATE UNIQUE INDEX uk_allocations_active_bed ON allocations (bed_id) WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX uk_allocations_active_tenant ON allocations (tenant_id) WHERE status = 'ACTIVE';
CREATE INDEX idx_allocations_tenant_start ON allocations (tenant_id, start_date DESC);
CREATE INDEX idx_allocations_property_status ON allocations (property_id, status);
CREATE INDEX idx_allocations_expected_end ON allocations (expected_end_date) WHERE status = 'ACTIVE';

-- ---------------------------------------------------------------------
-- Billing: invoices (rent / deposit), line items (charges & discounts), payments, refunds
-- ---------------------------------------------------------------------
CREATE SEQUENCE invoice_number_seq;
CREATE SEQUENCE receipt_number_seq;
CREATE SEQUENCE refund_reference_seq;

CREATE TABLE invoices (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number       VARCHAR(30)    NOT NULL,
    organization_id      BIGINT         NOT NULL REFERENCES organizations (id),
    property_id          BIGINT         NOT NULL REFERENCES properties (id),
    tenant_id            BIGINT         NOT NULL REFERENCES tenants (id),
    allocation_id        BIGINT         NOT NULL REFERENCES allocations (id),
    invoice_type         VARCHAR(20)    NOT NULL,
    billing_month        DATE,                         -- first day of the billed month (RENT only)
    period_start         DATE,
    period_end           DATE,
    issue_date           DATE           NOT NULL,
    due_date             DATE           NOT NULL,
    status               VARCHAR(20)    NOT NULL,
    subtotal             NUMERIC(12, 2) NOT NULL,
    discount_total       NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_amount         NUMERIC(12, 2) NOT NULL,
    amount_paid          NUMERIC(12, 2) NOT NULL DEFAULT 0,
    currency             VARCHAR(3)     NOT NULL DEFAULT 'INR',
    notes                VARCHAR(500),
    voided_at            TIMESTAMPTZ,
    void_reason          VARCHAR(255),
    created_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_by           BIGINT,
    version              BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_invoices_number UNIQUE (invoice_number),
    CONSTRAINT ck_invoices_type CHECK (invoice_type IN ('RENT', 'SECURITY_DEPOSIT')),
    CONSTRAINT ck_invoices_status CHECK (status IN ('ISSUED', 'PARTIALLY_PAID', 'PAID', 'OVERDUE', 'VOID')),
    CONSTRAINT ck_invoices_totals CHECK (total_amount = subtotal - discount_total),
    CONSTRAINT ck_invoices_discount CHECK (discount_total >= 0 AND discount_total <= subtotal),
    CONSTRAINT ck_invoices_paid CHECK (amount_paid >= 0 AND amount_paid <= total_amount),
    CONSTRAINT ck_invoices_rent_month CHECK (invoice_type <> 'RENT' OR billing_month IS NOT NULL)
);
-- idempotent billing: one live rent invoice per allocation per month, one deposit invoice per allocation
CREATE UNIQUE INDEX uk_invoices_rent_month ON invoices (allocation_id, billing_month)
    WHERE invoice_type = 'RENT' AND status <> 'VOID';
CREATE UNIQUE INDEX uk_invoices_deposit ON invoices (allocation_id)
    WHERE invoice_type = 'SECURITY_DEPOSIT' AND status <> 'VOID';
CREATE INDEX idx_invoices_tenant_status ON invoices (tenant_id, status);
CREATE INDEX idx_invoices_property_month ON invoices (property_id, billing_month);
CREATE INDEX idx_invoices_open_due ON invoices (due_date) WHERE status IN ('ISSUED', 'PARTIALLY_PAID');

CREATE TABLE invoice_line_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT         NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    line_type   VARCHAR(20)    NOT NULL,
    description VARCHAR(255)   NOT NULL,
    amount      NUMERIC(12, 2) NOT NULL,
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by  BIGINT,
    CONSTRAINT ck_line_items_type CHECK (line_type IN
        ('RENT', 'SECURITY_DEPOSIT', 'ELECTRICITY', 'FOOD', 'LAUNDRY', 'LATE_FEE', 'OTHER', 'DISCOUNT')),
    CONSTRAINT ck_line_items_amount CHECK (amount > 0)
);
CREATE INDEX idx_line_items_invoice ON invoice_line_items (invoice_id);

CREATE TABLE payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number      VARCHAR(30)    NOT NULL,
    organization_id     BIGINT         NOT NULL REFERENCES organizations (id),
    property_id         BIGINT         NOT NULL REFERENCES properties (id),
    tenant_id           BIGINT         NOT NULL REFERENCES tenants (id),
    invoice_id          BIGINT         NOT NULL REFERENCES invoices (id),
    idempotency_key     VARCHAR(100)   NOT NULL,
    request_fingerprint VARCHAR(64)    NOT NULL,   -- SHA-256 of the canonical request body
    amount              NUMERIC(12, 2) NOT NULL,
    refunded_amount     NUMERIC(12, 2) NOT NULL DEFAULT 0,
    method              VARCHAR(20)    NOT NULL,
    status              VARCHAR(20)    NOT NULL,
    external_reference  VARCHAR(100),               -- UPI/bank transaction id
    paid_at             TIMESTAMPTZ    NOT NULL,
    notes               VARCHAR(500),
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_by          BIGINT,
    version             BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_payments_receipt UNIQUE (receipt_number),
    CONSTRAINT uk_payments_idempotency UNIQUE (organization_id, idempotency_key),
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_refunded CHECK (refunded_amount >= 0 AND refunded_amount <= amount),
    CONSTRAINT ck_payments_method CHECK (method IN ('CASH', 'UPI', 'CARD', 'BANK_TRANSFER', 'CHEQUE')),
    CONSTRAINT ck_payments_status CHECK (status IN ('COMPLETED', 'PARTIALLY_REFUNDED', 'REFUNDED'))
);
CREATE UNIQUE INDEX uk_payments_external_reference ON payments (organization_id, method, external_reference)
    WHERE external_reference IS NOT NULL;
CREATE INDEX idx_payments_invoice ON payments (invoice_id);
CREATE INDEX idx_payments_tenant_paid ON payments (tenant_id, paid_at DESC);
CREATE INDEX idx_payments_property_paid ON payments (property_id, paid_at DESC);

CREATE TABLE refunds (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_reference    VARCHAR(30)    NOT NULL,
    organization_id     BIGINT         NOT NULL REFERENCES organizations (id),
    payment_id          BIGINT         NOT NULL REFERENCES payments (id),
    amount              NUMERIC(12, 2) NOT NULL,
    reason              VARCHAR(255)   NOT NULL,
    idempotency_key     VARCHAR(100)   NOT NULL,
    request_fingerprint VARCHAR(64)    NOT NULL,
    refunded_at         TIMESTAMPTZ    NOT NULL,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by          BIGINT,
    CONSTRAINT uk_refunds_reference UNIQUE (refund_reference),
    CONSTRAINT uk_refunds_idempotency UNIQUE (organization_id, idempotency_key),
    CONSTRAINT ck_refunds_amount CHECK (amount > 0)
);
CREATE INDEX idx_refunds_payment ON refunds (payment_id);

