    assigned_by BIGINT REFERENCES users (id),
    CONSTRAINT uk_property_assignments UNIQUE (property_id, user_id)
);
CREATE INDEX idx_property_assignments_user ON property_assignments (user_id);

CREATE TABLE buildings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id BIGINT       NOT NULL REFERENCES properties (id),
    code        VARCHAR(20)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_buildings_property_code UNIQUE (property_id, code)
);

CREATE TABLE floors (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id  BIGINT      NOT NULL REFERENCES buildings (id),
    floor_number INTEGER     NOT NULL,
    label        VARCHAR(50),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by   BIGINT,
    updated_by   BIGINT,
    version      BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_floors_building_number UNIQUE (building_id, floor_number)
);

CREATE TABLE rooms (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id       BIGINT        NOT NULL REFERENCES properties (id),  -- denormalised for scoping/queries
    floor_id          BIGINT        NOT NULL REFERENCES floors (id),
    room_number       VARCHAR(20)   NOT NULL,
    room_type         VARCHAR(20)   NOT NULL,
    capacity          INTEGER       NOT NULL,
    monthly_rent      NUMERIC(12, 2) NOT NULL,
    security_deposit  NUMERIC(12, 2) NOT NULL,
    air_conditioned   BOOLEAN       NOT NULL DEFAULT FALSE,
    attached_bathroom BOOLEAN       NOT NULL DEFAULT FALSE,
    status            VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by        BIGINT,
    updated_by        BIGINT,
    deleted_at        TIMESTAMPTZ,
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_rooms_type CHECK (room_type IN ('SINGLE', 'DOUBLE', 'TRIPLE', 'QUAD', 'DORMITORY')),
    CONSTRAINT ck_rooms_capacity CHECK (capacity BETWEEN 1 AND 20),
    CONSTRAINT ck_rooms_rent CHECK (monthly_rent >= 0 AND security_deposit >= 0),
    CONSTRAINT ck_rooms_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE UNIQUE INDEX uk_rooms_property_number ON rooms (property_id, room_number) WHERE deleted_at IS NULL;
CREATE INDEX idx_rooms_floor ON rooms (floor_id) WHERE deleted_at IS NULL;

CREATE TABLE beds (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT      NOT NULL REFERENCES rooms (id),
    property_id BIGINT      NOT NULL REFERENCES properties (id),
    bed_code    VARCHAR(10) NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    deleted_at  TIMESTAMPTZ,
    version     BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_beds_status CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'RESERVED', 'MAINTENANCE'))
);
CREATE UNIQUE INDEX uk_beds_room_code ON beds (room_id, bed_code) WHERE deleted_at IS NULL;
CREATE INDEX idx_beds_property_status ON beds (property_id, status) WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------
