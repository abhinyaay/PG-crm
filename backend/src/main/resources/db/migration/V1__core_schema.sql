    (3, 'MANAGER',        'Runs day-to-day operations of assigned properties'),
    (4, 'STAFF',          'Works maintenance/complaint tickets for assigned properties'),
    (5, 'TENANT',         'Resident with self-service portal access');

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     BIGINT       REFERENCES organizations (id),
    role_id             SMALLINT     NOT NULL REFERENCES roles (id),
    email               VARCHAR(255) NOT NULL,
    password_hash       VARCHAR(100) NOT NULL,
    full_name           VARCHAR(150) NOT NULL,
    phone               VARCHAR(20),
    status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    last_login_at       TIMESTAMPTZ,
    password_changed_at TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_by          BIGINT,
    deleted_at          TIMESTAMPTZ,
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    -- every non-platform user must belong to an organization
    CONSTRAINT ck_users_org_required CHECK (role_id = 1 OR organization_id IS NOT NULL)
);
-- emails are normalised to lower case by the application; index enforces it too
CREATE UNIQUE INDEX uk_users_email ON users (lower(email)) WHERE deleted_at IS NULL;
CREATE INDEX idx_users_org_role ON users (organization_id, role_id) WHERE deleted_at IS NULL;

CREATE TABLE refresh_tokens (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT      NOT NULL REFERENCES users (id),
    token_hash           VARCHAR(64) NOT NULL,            -- SHA-256 hex; raw token never stored
    family_id            UUID        NOT NULL,            -- rotation chain, used for reuse detection
    expires_at           TIMESTAMPTZ NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at           TIMESTAMPTZ,
    revoked_reason       VARCHAR(30),
    replaced_by_token_id BIGINT REFERENCES refresh_tokens (id),
    created_by_ip        VARCHAR(45),
    user_agent           VARCHAR(255),
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_expires ON refresh_tokens (expires_at);

-- ---------------------------------------------------------------------
-- Property hierarchy: property -> building -> floor -> room -> bed
-- ---------------------------------------------------------------------
CREATE TABLE properties (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organizations (id),
    code            VARCHAR(30)  NOT NULL,
    name            VARCHAR(150) NOT NULL,
    description     TEXT,
    property_type   VARCHAR(20)  NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    address_line1   VARCHAR(255) NOT NULL,
    address_line2   VARCHAR(255),
    city            VARCHAR(100) NOT NULL,
    state           VARCHAR(100) NOT NULL,
    postal_code     VARCHAR(12)  NOT NULL,
    country         VARCHAR(60)  NOT NULL DEFAULT 'India',
    contact_phone   VARCHAR(20),
    rent_due_day    INTEGER      NOT NULL DEFAULT 5,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      BIGINT,
    updated_by      BIGINT,
    deleted_at      TIMESTAMPTZ,
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_properties_type CHECK (property_type IN ('MEN', 'WOMEN', 'CO_LIVING')),
    CONSTRAINT ck_properties_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'UNDER_RENOVATION')),
    CONSTRAINT ck_properties_rent_due_day CHECK (rent_due_day BETWEEN 1 AND 28)
);
CREATE UNIQUE INDEX uk_properties_org_code ON properties (organization_id, code) WHERE deleted_at IS NULL;
CREATE INDEX idx_properties_org_status ON properties (organization_id, status) WHERE deleted_at IS NULL;
CREATE INDEX idx_properties_city ON properties (lower(city)) WHERE deleted_at IS NULL;

-- managers & staff are scoped to the properties they are assigned to
CREATE TABLE property_assignments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id BIGINT      NOT NULL REFERENCES properties (id),
    user_id     BIGINT      NOT NULL REFERENCES users (id),
