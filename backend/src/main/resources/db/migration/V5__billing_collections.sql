-- ---------------------------------------------------------------------
-- Shared CHECK supersets (the move-out work uses the same sets)
-- ---------------------------------------------------------------------
ALTER TABLE invoice_line_items DROP CONSTRAINT ck_line_items_type;
ALTER TABLE invoice_line_items ADD CONSTRAINT ck_line_items_type CHECK (line_type IN
    ('RENT', 'SECURITY_DEPOSIT', 'ELECTRICITY', 'FOOD', 'LAUNDRY', 'LATE_FEE', 'OTHER', 'DISCOUNT', 'PARKING',
     'INTERNET', 'DEDUCTION', 'NOTICE_SHORTFALL', 'DAMAGE'));

ALTER TABLE payments DROP CONSTRAINT ck_payments_method;
ALTER TABLE payments ADD CONSTRAINT ck_payments_method CHECK (method IN
    ('CASH', 'UPI', 'CARD', 'BANK_TRANSFER', 'CHEQUE', 'AUTOPAY', 'DEPOSIT_ADJUSTMENT'));

-- ---------------------------------------------------------------------
-- Billing policy per property (absence of a row = configured defaults)
-- ---------------------------------------------------------------------
CREATE TABLE property_billing_policies (
    property_id              BIGINT         PRIMARY KEY REFERENCES properties (id),
    organization_id          BIGINT         NOT NULL REFERENCES organizations (id),
    late_fee_enabled         BOOLEAN        NOT NULL DEFAULT FALSE,
    late_fee_type            VARCHAR(20)    NOT NULL DEFAULT 'FLAT',      -- FLAT | PERCENT_OF_RENT | PER_DAY
    late_fee_value           NUMERIC(12, 2) NOT NULL DEFAULT 0,          -- INR, percent, or INR per day
    late_fee_cap             NUMERIC(12, 2),                             -- max cumulative late fee per invoice
    grace_days               INTEGER        NOT NULL DEFAULT 0,
    -- move-in invoices issued after the rent due day are due the day they are issued: they get this extra grace
    move_in_grace_days       INTEGER        NOT NULL DEFAULT 7,
    late_fee_on_move_in      BOOLEAN        NOT NULL DEFAULT FALSE,       -- charge late fees on prorated move-in rent?
    due_reminder_days_before INTEGER        NOT NULL DEFAULT 3,
    overdue_reminder_offsets INTEGER[]      NOT NULL DEFAULT '{1,5,10}',
    upi_vpa                  VARCHAR(100),
    upi_payee_name           VARCHAR(100),
    created_at               TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by               BIGINT,
    updated_by               BIGINT,
    version                  BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_pbp_late_fee_type CHECK (late_fee_type IN ('FLAT', 'PERCENT_OF_RENT', 'PER_DAY')),
    CONSTRAINT ck_pbp_late_fee_value CHECK (late_fee_value >= 0
        AND (late_fee_type <> 'PERCENT_OF_RENT' OR late_fee_value <= 100)),
    CONSTRAINT ck_pbp_late_fee_cap CHECK (late_fee_cap IS NULL OR late_fee_cap > 0),
    CONSTRAINT ck_pbp_grace CHECK (grace_days BETWEEN 0 AND 31 AND move_in_grace_days BETWEEN 0 AND 31),
    CONSTRAINT ck_pbp_due_reminder CHECK (due_reminder_days_before BETWEEN 0 AND 15),
    CONSTRAINT ck_pbp_offsets CHECK (cardinality(overdue_reminder_offsets) <= 10),
    CONSTRAINT ck_pbp_upi_vpa CHECK (upi_vpa IS NULL OR upi_vpa ~ '^[A-Za-z0-9._-]{2,255}@[A-Za-z0-9]{2,64}$')
);
CREATE INDEX idx_pbp_organization ON property_billing_policies (organization_id);

-- ---------------------------------------------------------------------
-- Late-fee ledger: one CHARGE per invoice per period key (idempotent job), WAIVERs by managers
-- ---------------------------------------------------------------------
CREATE TABLE late_fee_entries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT         NOT NULL REFERENCES organizations (id),
    invoice_id      BIGINT         NOT NULL REFERENCES invoices (id),
    line_item_id    BIGINT         NOT NULL REFERENCES invoice_line_items (id),
    kind            VARCHAR(10)    NOT NULL,          -- CHARGE | WAIVER
    rule            VARCHAR(20),                      -- late-fee type that produced a CHARGE
    period_key      DATE,                             -- idempotency key of a CHARGE
    amount          NUMERIC(12, 2) NOT NULL,
    reason          VARCHAR(255),
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by      BIGINT,
    CONSTRAINT ck_late_fee_kind CHECK (kind IN ('CHARGE', 'WAIVER')),
    CONSTRAINT ck_late_fee_amount CHECK (amount > 0),
    CONSTRAINT ck_late_fee_period CHECK ((kind = 'CHARGE') = (period_key IS NOT NULL)),
    CONSTRAINT ck_late_fee_rule CHECK (rule IS NULL OR rule IN ('FLAT', 'PERCENT_OF_RENT', 'PER_DAY'))
);
CREATE UNIQUE INDEX uk_late_fee_invoice_period ON late_fee_entries (invoice_id, period_key) WHERE kind = 'CHARGE';
CREATE INDEX idx_late_fee_invoice ON late_fee_entries (invoice_id);

-- ---------------------------------------------------------------------
-- Tenant "I've paid" claims, verified by a manager into a real payment
-- ---------------------------------------------------------------------
CREATE SEQUENCE payment_claim_seq;
CREATE TABLE payment_claims (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_reference      VARCHAR(30)    NOT NULL,                 -- PCL-202610-000001
    organization_id      BIGINT         NOT NULL REFERENCES organizations (id),
    property_id          BIGINT         NOT NULL REFERENCES properties (id),
    tenant_id            BIGINT         NOT NULL REFERENCES tenants (id),
    invoice_id           BIGINT         NOT NULL REFERENCES invoices (id),
    submitted_by_user_id BIGINT         NOT NULL REFERENCES users (id),
    amount               NUMERIC(12, 2) NOT NULL,
    approved_amount      NUMERIC(12, 2),
    method               VARCHAR(20)    NOT NULL,
    utr                  VARCHAR(40),
    paid_on              DATE           NOT NULL,
    tenant_note          VARCHAR(500),
    proof_storage_key    VARCHAR(500),                            -- used once file storage exists
    status               VARCHAR(20)    NOT NULL DEFAULT 'SUBMITTED',
    reviewed_by          BIGINT REFERENCES users (id),
    reviewed_at          TIMESTAMPTZ,
    review_note          VARCHAR(500),
    rejection_reason     VARCHAR(255),
    payment_id           BIGINT REFERENCES payments (id),
    created_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_by           BIGINT,
    version              BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_payment_claims_reference UNIQUE (claim_reference),
    CONSTRAINT ck_payment_claims_amount CHECK (amount > 0 AND (approved_amount IS NULL
        OR (approved_amount > 0 AND approved_amount <= amount))),
    CONSTRAINT ck_payment_claims_method CHECK (method IN ('UPI', 'BANK_TRANSFER', 'CASH', 'CHEQUE')),
    CONSTRAINT ck_payment_claims_status CHECK (status IN ('SUBMITTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_payment_claims_utr CHECK ((method = 'CASH') = (utr IS NULL)),
    CONSTRAINT ck_payment_claims_approved CHECK ((status = 'APPROVED') = (payment_id IS NOT NULL))
);
CREATE UNIQUE INDEX uk_payment_claims_open_invoice ON payment_claims (invoice_id) WHERE status = 'SUBMITTED';
CREATE UNIQUE INDEX uk_payment_claims_utr ON payment_claims (organization_id, upper(utr))
    WHERE utr IS NOT NULL AND status IN ('SUBMITTED', 'APPROVED');
CREATE INDEX idx_payment_claims_property_status ON payment_claims (property_id, status, created_at);
CREATE INDEX idx_payment_claims_tenant ON payment_claims (tenant_id, created_at DESC);

-- ---------------------------------------------------------------------
-- Recurring monthly add-ons, snapshotted into rent invoices as line items
-- ---------------------------------------------------------------------
CREATE TABLE recurring_charges (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     BIGINT         NOT NULL REFERENCES organizations (id),
    property_id         BIGINT         NOT NULL REFERENCES properties (id),
    tenant_id           BIGINT         NOT NULL REFERENCES tenants (id),
    allocation_id       BIGINT REFERENCES allocations (id),        -- NULL = follows the tenant across transfers
    line_type           VARCHAR(20)    NOT NULL,
    description         VARCHAR(255)   NOT NULL,
    amount              NUMERIC(12, 2) NOT NULL,
    start_month         DATE           NOT NULL,                  -- first day of month
    end_month           DATE,                                     -- inclusive, first day of month
    prorate_first_month BOOLEAN        NOT NULL DEFAULT FALSE,
    active              BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_by          BIGINT,
    version             BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_recurring_charges_type CHECK (line_type IN ('FOOD', 'LAUNDRY', 'PARKING', 'INTERNET', 'OTHER')),
    CONSTRAINT ck_recurring_charges_amount CHECK (amount > 0),
    CONSTRAINT ck_recurring_charges_months CHECK (extract(DAY FROM start_month) = 1
        AND (end_month IS NULL OR (extract(DAY FROM end_month) = 1 AND end_month >= start_month)))
);
CREATE INDEX idx_recurring_charges_tenant ON recurring_charges (tenant_id) WHERE active;

-- ---------------------------------------------------------------------
-- AutoPay: mandates, debit attempts, provider webhook log
-- ---------------------------------------------------------------------
CREATE TABLE payment_mandates (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id      BIGINT         NOT NULL REFERENCES organizations (id),
    property_id          BIGINT         NOT NULL REFERENCES properties (id),
    tenant_id            BIGINT         NOT NULL REFERENCES tenants (id),
    provider             VARCHAR(20)    NOT NULL,
    provider_mandate_id  VARCHAR(100)   NOT NULL,
    provider_customer_id VARCHAR(100),
    provider_token_id    VARCHAR(100),
    method               VARCHAR(20)    NOT NULL,
    max_amount           NUMERIC(12, 2) NOT NULL,
    status               VARCHAR(30)    NOT NULL DEFAULT 'PENDING_AUTHORISATION',
    authorisation_url    VARCHAR(500),
    debit_day_offset     INTEGER        NOT NULL DEFAULT 0,
    status_reason        VARCHAR(255),
    authorised_at        TIMESTAMPTZ,
    paused_at            TIMESTAMPTZ,
    cancelled_at         TIMESTAMPTZ,
    created_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_by           BIGINT,
    version              BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_payment_mandates_provider UNIQUE (provider, provider_mandate_id),
    CONSTRAINT ck_payment_mandates_method CHECK (method IN ('UPI_AUTOPAY', 'ENACH', 'CARD')),
    CONSTRAINT ck_payment_mandates_status CHECK (status IN
        ('PENDING_AUTHORISATION', 'ACTIVE', 'PAUSED', 'CANCELLED', 'FAILED')),
    CONSTRAINT ck_payment_mandates_amount CHECK (max_amount > 0),
    CONSTRAINT ck_payment_mandates_offset CHECK (debit_day_offset BETWEEN 0 AND 10)
);
CREATE UNIQUE INDEX uk_payment_mandates_live_tenant ON payment_mandates (tenant_id)
    WHERE status IN ('PENDING_AUTHORISATION', 'ACTIVE', 'PAUSED');
CREATE INDEX idx_payment_mandates_property_status ON payment_mandates (property_id, status);
CREATE INDEX idx_payment_mandates_token ON payment_mandates (provider, provider_token_id) WHERE provider_token_id IS NOT NULL;

CREATE TABLE autopay_attempts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     BIGINT         NOT NULL REFERENCES organizations (id),
    property_id         BIGINT         NOT NULL REFERENCES properties (id),
    mandate_id          BIGINT         NOT NULL REFERENCES payment_mandates (id),
    invoice_id          BIGINT         NOT NULL REFERENCES invoices (id),
    tenant_id           BIGINT         NOT NULL REFERENCES tenants (id),
    provider            VARCHAR(20)    NOT NULL,
    amount              NUMERIC(12, 2) NOT NULL,
    attempt_no          INTEGER        NOT NULL,
    attempt_date        DATE           NOT NULL,
    provider_payment_id VARCHAR(100),
    status              VARCHAR(20)    NOT NULL DEFAULT 'SCHEDULED',
    failure_reason      VARCHAR(255),
    payment_id          BIGINT REFERENCES payments (id),
    completed_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version             BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_autopay_attempts_invoice_no UNIQUE (invoice_id, attempt_no),
    CONSTRAINT uk_autopay_attempts_invoice_day UNIQUE (invoice_id, attempt_date),
    CONSTRAINT ck_autopay_attempts_status CHECK (status IN ('SCHEDULED', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_autopay_attempts_no CHECK (attempt_no BETWEEN 1 AND 3),
    CONSTRAINT ck_autopay_attempts_amount CHECK (amount > 0)
);
CREATE UNIQUE INDEX uk_autopay_attempts_provider_payment ON autopay_attempts (provider, provider_payment_id)
    WHERE provider_payment_id IS NOT NULL;
CREATE INDEX idx_autopay_attempts_mandate ON autopay_attempts (mandate_id, created_at DESC);
CREATE INDEX idx_autopay_attempts_property ON autopay_attempts (property_id, created_at DESC);

CREATE TABLE payment_webhook_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider    VARCHAR(20)  NOT NULL,
    event_id    VARCHAR(150) NOT NULL,
    event_type  VARCHAR(60)  NOT NULL,
    received_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_payment_webhook_events UNIQUE (provider, event_id)
);
