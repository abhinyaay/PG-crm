-- =====================================================================
-- V7: biometric entry / exit (optional module, off by default per property)
--   * access_settings      per-property switch, exit mode, default daily entry limit
--   * access_devices       registered terminals (ZKTeco/eSSL ADMS push or generic bridge/webhook)
--   * access_credentials   device user id (PIN) <-> resident / staff mapping; templates never leave the device
--   * access_member_limits per-resident daily entry limit override
--   * access_events        append-only gate log; idempotent per device punch
--   * access_presence      view: last ALLOWED event per person -> IN / OUT
-- =====================================================================

CREATE TABLE access_settings (
    property_id            BIGINT      PRIMARY KEY REFERENCES properties (id),
    enabled                BOOLEAN     NOT NULL DEFAULT FALSE,
    exit_mode              VARCHAR(20) NOT NULL DEFAULT 'DEVICE_OR_BUTTON',
    max_entries_per_day    INTEGER,                        -- NULL = unlimited
    track_staff            BOOLEAN     NOT NULL DEFAULT FALSE,
    device_offline_minutes INTEGER     NOT NULL DEFAULT 15,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by             BIGINT,
    updated_by             BIGINT,
    version                BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_access_settings_exit_mode CHECK (exit_mode IN ('DEVICE', 'BUTTON', 'DEVICE_OR_BUTTON')),
    CONSTRAINT ck_access_settings_limit CHECK (max_entries_per_day IS NULL OR max_entries_per_day >= 1),
    CONSTRAINT ck_access_settings_offline CHECK (device_offline_minutes BETWEEN 1 AND 10080)
);

CREATE TABLE access_devices (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     BIGINT       NOT NULL REFERENCES organizations (id),
    property_id         BIGINT       NOT NULL REFERENCES properties (id),
    name                VARCHAR(100) NOT NULL,
    vendor              VARCHAR(20)  NOT NULL,
    serial_number       VARCHAR(64)  NOT NULL,               -- normalised to upper case by the application
    direction           VARCHAR(10)  NOT NULL,
    time_zone           VARCHAR(40)  NOT NULL DEFAULT 'Asia/Kolkata',  -- zone of the device clock (ATTLOG has none)
    api_key_hash        VARCHAR(64)  NOT NULL,               -- SHA-256 hex of the bridge key; the key is shown once
    status              VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
    last_seen_at        TIMESTAMPTZ,
    last_ip             VARCHAR(45),
    attlog_stamp        VARCHAR(32),                         -- last ADMS ATTLOG stamp the device reported
    offline_alerted_at  TIMESTAMPTZ,                         -- one offline alert per outage; cleared when seen again
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_by          BIGINT,
    deleted_at          TIMESTAMPTZ,
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_access_devices_vendor CHECK (vendor IN ('ZKTECO_ADMS', 'ESSL_ADMS', 'GENERIC_WEBHOOK')),
    CONSTRAINT ck_access_devices_direction CHECK (direction IN ('ENTRY', 'EXIT', 'BOTH')),
    CONSTRAINT ck_access_devices_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);
-- devices identify themselves only by serial number, so it is unique platform-wide
CREATE UNIQUE INDEX uk_access_devices_serial ON access_devices (upper(serial_number)) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uk_access_devices_api_key ON access_devices (api_key_hash) WHERE deleted_at IS NULL;
CREATE INDEX idx_access_devices_property ON access_devices (property_id) WHERE deleted_at IS NULL;

CREATE TABLE access_credentials (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id     BIGINT      NOT NULL REFERENCES properties (id),
    device_user_id  VARCHAR(24) NOT NULL,                    -- the PIN / user id typed when enrolling on the device
    tenant_id       BIGINT      REFERENCES tenants (id),
    user_id         BIGINT      REFERENCES users (id),       -- staff member (only used when track_staff)
    credential_type VARCHAR(20) NOT NULL DEFAULT 'FINGERPRINT',
    status          VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    enrolled_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by      BIGINT,
    revoked_at      TIMESTAMPTZ,
    revoked_by      BIGINT,
    CONSTRAINT ck_access_credentials_owner CHECK ((tenant_id IS NULL) <> (user_id IS NULL)),
    CONSTRAINT ck_access_credentials_type CHECK (credential_type IN ('FINGERPRINT', 'FACE', 'CARD')),
    CONSTRAINT ck_access_credentials_status CHECK (status IN ('ACTIVE', 'REVOKED'))
);
CREATE UNIQUE INDEX uk_access_credentials_active_pin ON access_credentials (property_id, device_user_id)
    WHERE status = 'ACTIVE';
CREATE INDEX idx_access_credentials_tenant ON access_credentials (tenant_id) WHERE tenant_id IS NOT NULL;
CREATE INDEX idx_access_credentials_user ON access_credentials (user_id) WHERE user_id IS NOT NULL;

CREATE TABLE access_member_limits (
    tenant_id           BIGINT      PRIMARY KEY REFERENCES tenants (id),
    max_entries_per_day INTEGER,                             -- NULL = unlimited (overrides the property default)
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    CONSTRAINT ck_access_member_limits_limit CHECK (max_entries_per_day IS NULL OR max_entries_per_day >= 1)
);

CREATE TABLE access_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organizations (id),
    property_id     BIGINT       NOT NULL REFERENCES properties (id),
    device_id       BIGINT       REFERENCES access_devices (id),
    tenant_id       BIGINT       REFERENCES tenants (id),
    user_id         BIGINT       REFERENCES users (id),
    device_user_id  VARCHAR(24),
    direction       VARCHAR(10)  NOT NULL,
    method          VARCHAR(20)  NOT NULL,
    occurred_at     TIMESTAMPTZ  NOT NULL,
    received_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    result          VARCHAR(30)  NOT NULL,
    reason          VARCHAR(500),
    recorded_by     BIGINT       REFERENCES users (id),      -- staff member for BUTTON (on behalf) / MANUAL_OVERRIDE
    CONSTRAINT ck_access_events_direction CHECK (direction IN ('ENTRY', 'EXIT')),
    CONSTRAINT ck_access_events_method CHECK (method IN ('FINGERPRINT', 'FACE', 'CARD', 'BUTTON', 'MANUAL_OVERRIDE')),
    CONSTRAINT ck_access_events_result CHECK (result IN ('ALLOWED', 'DENIED_LIMIT_EXCEEDED', 'DENIED_NOT_RESIDENT',
                                                          'DENIED_DISABLED', 'UNKNOWN_CREDENTIAL', 'IGNORED_EXIT_MODE'))
);
-- devices re-send their logs (reconnects, ATTLOGStamp resets): the same punch must be stored once
CREATE UNIQUE INDEX uk_access_events_device_punch ON access_events (device_id, device_user_id, occurred_at, direction)
    WHERE device_id IS NOT NULL;
CREATE INDEX idx_access_events_property_time ON access_events (property_id, occurred_at DESC);
CREATE INDEX idx_access_events_tenant_time ON access_events (tenant_id, occurred_at DESC) WHERE tenant_id IS NOT NULL;
CREATE INDEX idx_access_events_presence ON access_events (property_id, tenant_id, user_id, occurred_at DESC, id DESC)
    WHERE result = 'ALLOWED';

-- Who is inside: the latest ALLOWED event of every person per property (ENTRY -> IN, EXIT -> OUT).
CREATE VIEW access_presence AS
SELECT DISTINCT ON (e.property_id, e.tenant_id, e.user_id)
       e.organization_id,
       e.property_id,
       e.tenant_id,
       e.user_id,
       CASE WHEN e.direction = 'ENTRY' THEN 'IN' ELSE 'OUT' END AS presence,
       e.occurred_at AS since,
       e.id          AS event_id,
       e.method,
       e.device_id
FROM access_events e
WHERE e.result = 'ALLOWED'
  AND (e.tenant_id IS NOT NULL OR e.user_id IS NOT NULL)
ORDER BY e.property_id, e.tenant_id, e.user_id, e.occurred_at DESC, e.id DESC;
